package ru.lct.heat.routing;

import lombok.Getter;
import lombok.Setter;

/**
 * Параметры алгоритма трассировки. Биндится из {@code app.routing.*} (см. application.yml),
 * но ядро может использоваться и без Spring — поэтому это обычный POJO с дефолтами.
 */
@Getter
@Setter
public class RoutingParams {

    /** Штраф за поворот, в метрах-эквивалентах трубы на каждые 45° поворота. */
    private double turnPenaltyMPer45Deg = 4.0;

    /** Радиус поиска соседей в графе видимости, м (плюс расстояние до ближайшей цели). */
    private double neighborRadiusM = 150.0;

    /**
     * Запас между вершинами графа (точками поворота) и границей зоны отступа, м. Трасса ищется при ДУ
     * по расходу точки, а после объединения в магистраль ДУ и габарит растут (DN100→DN400: +0.43 м);
     * запас позволяет не перекладывать трассу. Проверка отрезков — всегда по точной зоне.
     */
    private double vertexClearanceEpsM = 0.5;

    /** Шаг уплотнения контура спецзоны спецпроходов (дороги, трамвай, коммуникации) для точек поворота, м. */
    private double specialZoneSampleStepM = 20.0;

    /** Шаг выборки кандидатов точек врезки вдоль существующей сети, м. */
    private double tieInSampleStepM = 10.0;

    /** Шаг выборки точек присоединения к уже построенному дереву вдоль его рёбер, м. */
    private double treeJoinSampleStepM = 10.0;

    /** Радиус целей на дереве = расстояние до ближайшей врезки × factor + extra, м. */
    private double treeJoinRadiusFactor = 2.0;
    private double treeJoinRadiusExtraM = 50.0;

    /** Минимальный зазор между осями новых участков (плюс ширина габарита), м. */
    private double newPipeClearanceM = 1.0;

    /**
     * Подход к зданию (§2.2): true — строго через ближайшую к точке границу полигона, другие точки
     * входа только если через ближайшую пути нет; false — A* выбирает точку входа по общей стоимости.
     */
    private boolean nearestEntryOnly = true;

    /**
     * При nearestEntryOnly: вход через ближайшую границу отвергается как «необоснованный обход» (§2.1),
     * если путь через неё длиннее лучшего пути через другую точку входа более чем в это число раз;
     * ≤ 1 — не проверять.
     */
    private double nearestEntryMaxDetourFactor = 2.0;

    /**
     * При nearestEntryOnly: обход через ближайшую границу отвергается, только если он ещё и длиннее
     * альтернативы не менее чем на это число метров (полная длина трубы до точки); мелкие «за угол»
     * остаются через ближайшую границу, как требует §2.2.
     */
    private double nearestEntryMinDetourM = 30.0;

    /** Сколько альтернативных точек входа в здание предлагать A* (ближайшая граница может быть во дворе). */
    private int maxApproaches = 12;

    /**
     * Сколько метров трассы допустимо доплатить за приведение угла поворота к 45°/90°.
     * Разъяснение оргов п. 19: удорожания нестандартных углов нет, 45° и 90° не обязательны, —
     * поэтому 0: угол приводится к 45°/90° только там, где это не удлиняет трассу.
     */
    private double snapMaxExtraM = 0.0;

    /**
     * Решётчатое выпрямление (все повороты 45°/90°, направления по ориентации здания/квартала):
     * ребро перекладывается, если удлиняется не более чем на эту долю; ≤ 0 — выключено.
     */
    private double rectifyMaxExtraFrac = 0.0;

    /** Шаг решётки выпрямления, м. */
    private double rectifyStepM = 2.0;

    /** Лимит раскрытий состояний решётки на одно ребро. */
    private int rectifyMaxExpansions = 80_000;

    /**
     * Группы ДУ для трассировки: маршрут ищется по карте препятствий наибольшего ДУ группы (чуть больший
     * габарит — безопасно), так карт мало и кэш видимости общий. Проверка результата — всегда по точному ДУ.
     */
    private String routingDiameterBuckets = "200,800,1400";

    /** Максимум проходов построения дерева с накоплением подсказок ДУ (пока остаются нарушения). */
    private int maxBuildPasses = 5;

    /** Проходов локальной оптимизации (переподключение точек) после жадного построения; 0 — выключено. */
    private int localSearchPasses = 2;

    /** Допуск привязки существующей камеры к участку (шум координат во входе), м. */
    private double chamberSnapTolM = 0.5;

    /** Ограничивать расчёт областью интереса (охват точек + ближайшая сеть + запас) — для входов масштаба города. */
    private boolean cropToAreaOfInterest = true;

    /** Запас области интереса вокруг охвата точек и ближайшей сети, м. */
    private double areaMarginM = 300.0;

    /** Минимальный размер области интереса, м. */
    private double areaMinExtentM = 1000.0;

    /** Сколько дополнительных детерминированно-случайных порядков подключения перебирать (0 — не перебирать). */
    private int randomOrderStrategies = 12;

    /** Нижняя граница числа случайных порядков (для больших входов). */
    private int randomOrderMin = 4;

    /** Бюджет: число случайных порядков ≈ budget / число точек (в пределах [min, randomOrderStrategies]). */
    private int randomOrderBudgetPoints = 240;

    /** Вариаций порядка от лучшего варианта (и вдвое меньше — от второго), масштабируется бюджетом по числу точек; 0 — выключено. */
    private int perturbationRounds = 8;

    /**
     * Бюджет перебора вариантов в проверках отрезков (детерминированная мера работы, не время): после его
     * исчерпания вариации порядка прекращаются. 0 — без ограничения. Это страховка от патологического входа,
     * а не способ ускорения: конкурсный датасет тратит 1.5 млн проверок, город из 120 точек — 9.4 млн,
     * 11.5 тыс. объектов — 5.2 млн, то есть на нормальных данных бюджет не срабатывает.
     */
    private long searchBudgetChecks = 40_000_000L;

    /** Ограничение параллелизма (0 — по числу ядер); для воспроизводимых замеров на слабом железе. */
    private int maxThreads = 0;

    /** Итераций вариаций (каждая — от текущих лучших; останавливаемся, если улучшения нет). */
    private int perturbationIterations = 3;

    /**
     * Максимальная доля совпадения трасс двух вариантов в выдаче (§6 «содержательно разные»): кандидат,
     * совпадающий с уже выбранным сильнее, берётся только если непохожих не осталось.
     */
    private double variantMaxOverlap = 0.8;

    /** Допуск, в пределах которого трассы считаются совпадающими, м. */
    private double variantOverlapToleranceM = 3.0;

    /**
     * Жёсткий порог: кандидат, совпадающий с уже выбранным сильнее, в выдачу не попадает вовсе —
     * §6 прямо говорит, что сдвиг той же трассы вариантом не считается, поэтому лучше выдать меньше.
     */
    private double variantHardMaxOverlap = 0.9;

    /**
     * Пробовать вариант с одним вводом от существующей сети. Проверено на датасете и синтетике: хуже
     * (score 12.85 против 11.80) — камера-врезка 5 млн эквивалентна ~24 м трубы, а общий ввод удлиняет
     * трассу сильнее. Оставлено как опция: один ввод может требоваться по условиям эксплуатации.
     */
    private boolean singleRootStrategy = false;

    /** Какие стратегии вариантов запускать (id через запятую: v1,v2,v3,v4); пусто — все. */
    private String enabledStrategies = "";

    /** Максимальное число раскрытий узла в A*, защита от зависания. */
    private int maxExpansions = 200_000;

    /** Лимит извлечений из очереди (≈ проверок видимости) на один поиск: ограничивает стоимость неудачного поиска. */
    private int maxChecksPerSearch = 1_500_000;

    /** Лимит раскрытий при перепрокладке нарушающего ребра (неудачный ремонт не должен стоить полного перебора). */
    private int repairMaxExpansions = 4_000;

    /**
     * Резервный поиск по мелкому растру, когда граф видимости не нашёл путь (стеснённая застройка:
     * коридор в 1–2 м между зонами отступа не имеет вершин контура). Шаг растра, м; 0 — выключено.
     *
     * <p>Экспериментально: находит пути, но на плотной реальной застройке даёт трассы, которые не проходят
     * независимый валидатор (пересечения спецзон), и заметно замедляет расчёт. По умолчанию выключен;
     * включать только вместе с проверкой результата валидатором.
     */
    private double fallbackGridStepM = 0;

    /** Запас окна растра вокруг старта и цели, м. */
    private double fallbackGridMarginM = 60.0;

    /** Предельный размер окна растра, м (дальше резервный поиск не запускается). */
    private double fallbackGridMaxExtentM = 600.0;

    /** Предельное число клеток растра. */
    private long fallbackGridMaxCells = 2_000_000L;

    /** Предельное число раскрытий в растровом поиске. */
    private int fallbackGridMaxExpansions = 400_000;

    /** На сколько клеток вперёд натягивается нить при упрощении растрового пути. */
    private int fallbackPullReachCells = 400;

    /** Максимальная длина сквозного пересечения спецзоны в растровом поиске, м. */
    private double fallbackJumpMaxM = 60.0;
}
